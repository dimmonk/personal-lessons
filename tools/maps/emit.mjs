// Writes a region as the classic script the app loads: one ring or place to a line (so a file stays under 800 lines), registered with FC.map.
import { writeFile, mkdir } from 'node:fs/promises';

const OUT = new URL('../../public/maps/', import.meta.url);
export const MAX_LINES = 780;

export function mapSource(R, built, note) {
  const quote = v => JSON.stringify(v);
  const head = { name: R.name, size: built.size.map(v => Math.round(v * 10) / 10), q: 10, land: R.land, draw: R.draw, labelled: R.labelled, source: note };
  if (built.frames.length) head.frames = built.frames;
  const lines = [
    `// ${R.name}: generated by tools/maps/build-maps.mjs (npm run maps) from ${note}. Do not edit by hand; change tools/maps/regions.mjs and build again.`,
    `// Each ring is the first point, then the step to every next one, in tenths of a unit of a ${built.size[0]}-wide map; north is up.`,
    `FC.map(${quote(R.id)}, {`,
    ...Object.entries(head).map(([k, v]) => `  ${k}: ${quote(v)},`),
    '  rings: [',
    ...built.rings.map((r, i) => `    ${quote(r)}${i < built.rings.length - 1 ? ',' : ''}`),
    '  ],',
    '  places: [',
    ...built.places.map((p, i) => `    ${quote(p)}${i < built.places.length - 1 ? ',' : ''}`),
    '  ]',
    '});',
    ''
  ];
  if (lines.length > MAX_LINES) throw new Error(`${R.id}: ${lines.length} lines, over the ${MAX_LINES} a file may hold`);
  return lines.join('\n');
}
export async function writeMap(R, source) {
  await mkdir(OUT, { recursive: true });
  await writeFile(new URL(`${R.id}.js`, OUT), source);
  return Buffer.byteLength(source);
}
